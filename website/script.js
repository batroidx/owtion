const switcher = document.querySelector("#language-switch");
const languageLabel = document.querySelector("#language-label");
const nav = document.querySelector("#main-nav");
const menuToggle = document.querySelector("#menu-toggle");
const languageKey = "owtion-website-language";

function setLanguage(language) {
  const dictionary = translations[language];
  document.documentElement.lang = language;
  document.title = dictionary.pageTitle;
  document.querySelector('meta[name="description"]').content = dictionary.pageDescription;
  languageLabel.textContent = dictionary.languageLabel;
  switcher.setAttribute("aria-label", dictionary.languageAria);
  nav.setAttribute("aria-label", dictionary.menuLabel);
  menuToggle.setAttribute("aria-label", nav.classList.contains("is-open") ? dictionary.menuClose : dictionary.menuOpen);
  document.querySelectorAll(".brand").forEach((brand) => brand.setAttribute("aria-label", dictionary.brandLabel));
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const translation = dictionary[element.dataset.i18n];
    if (translation) element.innerHTML = translation;
  });
  try {
    localStorage.setItem(languageKey, language);
  } catch (error) {
    console.warn("Could not save the website language preference.", error);
  }
}

let currentLanguage = "ru";
try {
  const savedLanguage = localStorage.getItem(languageKey);
  if (savedLanguage === "en" || savedLanguage === "ru") currentLanguage = savedLanguage;
} catch (error) {
  console.warn("Could not read the saved website language preference.", error);
}
setLanguage(currentLanguage);

switcher.addEventListener("click", () => {
  currentLanguage = currentLanguage === "ru" ? "en" : "ru";
  setLanguage(currentLanguage);
});

menuToggle.addEventListener("click", () => {
  const isOpen = nav.classList.toggle("is-open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
  menuToggle.setAttribute("aria-label", isOpen ? translations[currentLanguage].menuClose : translations[currentLanguage].menuOpen);
});

nav.addEventListener("click", (event) => {
  if (event.target instanceof HTMLAnchorElement) {
    nav.classList.remove("is-open");
    menuToggle.setAttribute("aria-expanded", "false");
    menuToggle.setAttribute("aria-label", translations[currentLanguage].menuOpen);
  }
});

if ("IntersectionObserver" in window && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  const observer = new IntersectionObserver((entries, currentObserver) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        currentObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));
} else {
  document.querySelectorAll(".reveal").forEach((element) => element.classList.add("is-visible"));
}
